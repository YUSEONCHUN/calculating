/**
 * (시도, 시군구) 명칭 → 법정동 시군구 코드(5자리) 목록 — 개편 전·후 코드가 함께 반환됨
 * salary_table.sigungu_code 처럼 코드로 수집된 데이터를 한글 주소로 조회할 때 사용
 */
function regionCodesForName($sido, $sigungu)
{
    static $rev = null;
    if ($rev === null) {
        $rev = array();
        foreach (regionCodeMap() as $code => $names) {
            $rev[$names[0] . '|' . $names[1]][] = $code;
        }
    }
    $key = $sido . '|' . $sigungu;
    return isset($rev[$key]) ? $rev[$key] : array();
}
